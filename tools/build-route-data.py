#!/usr/bin/env python3
"""Convert the Connected World kit's course contract into a classic game script.

  python3 tools/build-route-data.py

Reads  kit/connected/Wishweave-Connected-World-Kit/scenery/route.json  (never modified)
Writes game/connected/src/data/route.js  ->  WW.ROUTE

Why a script and not a fetched JSON file: game/index.html must also open from file:// and the simulation must load in
Node tests (tests/unit/load.cjs), so all data is a classic script on globalThis.WW.

Sign convention. The kit's "right" vector is [t.z, 0, -t.x]; under a three.js camera looking along the road it points
to the SCREEN-LEFT (checked by the kit-code inspection). The game uses screen-right as positive lateral, i.e.
right = [-t.z, 0, t.x]. So every kit `lateralOffset` is negated here (`lateral`), and the branch, which lies at kit
lateral +0..+5 m, is on the runner's LEFT. Positions are unchanged.

Points are packed as arrays: main [s, x, y, z, width, tx, ty, tz]; branch [s, x, y, z, width, tx, ty, tz, mainS].
"""
import hashlib
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(REPO, 'kit', 'connected', 'Wishweave-Connected-World-Kit', 'scenery', 'route.json')
OUT = os.path.join(REPO, 'game', 'connected', 'src', 'data', 'route.js')


def r6(v):
    return round(float(v), 6)


def pack(points, with_main):
    out = []
    for p in points:
        row = [r6(p['s']), r6(p['x']), r6(p['y']), r6(p['z']), r6(p['width'])] + [r6(v) for v in p['tangent']]
        if with_main:
            row.append(r6(p['mainS']))
        out.append(row)
    return out


def main():
    raw = open(SRC, 'rb').read()
    data = json.loads(raw)
    m = data['mainRoute']
    out = {
        'schema': data['schema'],
        'source': 'kit/connected/Wishweave-Connected-World-Kit/scenery/route.json',
        'sourceSha256': hashlib.sha256(raw).hexdigest(),
        'lateralSign': 'positive lateral = runner\'s screen-right (kit lateralOffset negated)',
        'main': {
            'id': 'main', 'width': m['width'], 'length': r6(m['length']),
            'points': pack(m['points'], False),
            'sectionOf': [p['sectionId'] for p in m['points']],
        },
        'spawn': {'s': m['spawn']['s'], 'position': [r6(v) for v in m['spawn']['position']]},
        'finish': {'s': r6(m['finish']['s']), 'position': [r6(v) for v in m['finish']['position']],
                   'forward': [r6(v) for v in m['finish']['forward']], 'width': m['finish']['width'],
                   'triggerDepth': m['finish']['triggerDepth']},
        'sections': [{'id': s['id'], 'name': s['name'], 'startS': r6(s['startS']), 'endS': r6(s['endS'])}
                     for s in data['sections']],
        'branches': [],
        'collectibles': [],
        'landmarks': [],
    }
    for b in data['branches']:
        out['branches'].append({
            'id': b['id'], 'name': b['name'], 'width': b['width'], 'length': r6(b['length']),
            'startS': r6(b['startS']), 'endS': r6(b['endS']), 'side': 'left',
            'points': pack(b['points'], True),
        })
    for c in data['collectibles']:
        out['collectibles'].append({
            'id': c['id'], 'type': c['type'], 'mainS': r6(c['mainS']), 'lateral': -c['lateralOffset'] + 0.0,
            'hover': c['hoverAboveRoad'], 'position': [r6(v) for v in c['position']],
        })
    for l in data['landmarks']:
        out['landmarks'].append({
            'id': l['id'], 'name': l['name'], 'mainS': r6(l['mainS']), 'lateral': -l['lateralOffset'] + 0.0,
            'radius': l['footprintRadius'], 'position': [r6(v) for v in l['position']],
        })
    text = ('/* GENERATED by tools/build-route-data.py from the Connected World kit route.json — do not hand-edit.\n'
            '   Course contract: metres, Y up, +Z forward. Positive lateral = the runner\'s screen-right.\n'
            '   main/branch points: [s, x, y, z, width, tx, ty, tz(, mainS)]. */\n'
            '(function (WW) {\n  \'use strict\';\n  WW.ROUTE = ' +
            json.dumps(out, separators=(',', ':')) + ';\n})(globalThis.WW = globalThis.WW || {});\n')
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote %s (%d bytes, %d main + %d branch points)' % (
        os.path.relpath(OUT, REPO), len(text), len(out['main']['points']),
        sum(len(b['points']) for b in out['branches'])))


if __name__ == '__main__':
    main()
