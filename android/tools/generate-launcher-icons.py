#!/usr/bin/env python3
"""Generate the Wishweave Wonders launcher icons from the approved front Purl art.

Source art (read-only): kit/Wishweave-Level1-Complete-Visual-Kit/assets/individual/purl-atlas/frame-01.png

Writes into android/app/src/main/res/:
  values/ic_launcher_background.xml           adaptive-icon background colour
  mipmap-anydpi-v26/ic_launcher{,_round}.xml  adaptive icon (background colour + foreground PNG)
  mipmap-<density>/ic_launcher_foreground.png 108 dp foreground layer, Purl inside the 66 dp safe zone
  mipmap-<density>/ic_launcher.png            legacy 48 dp rounded-square icon
  mipmap-<density>/ic_launcher_round.png      legacy 48 dp round icon

Usage (from anywhere): python3 android/tools/generate-launcher-icons.py
Requires Pillow. Output is deterministic for the same Pillow version and source PNG.
"""
from pathlib import Path
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

HERE = Path(__file__).resolve().parent
ANDROID = HERE.parent
REPO = ANDROID.parent
SOURCE = REPO / 'kit/Wishweave-Level1-Complete-Visual-Kit/assets/individual/purl-atlas/frame-01.png'
RES = ANDROID / 'app/src/main/res'

# Tapestry teal from the loom-city palette; the coral Purl reads clearly against it.
BACKGROUND_HEX = '#2F7470'
BACKGROUND_INNER = (72, 150, 141)    # lighter centre glow for the legacy (pre-composited) icons
DENSITIES = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0}
SS = 4                     # supersampling factor
ART_MAX_DP = 64            # Purl's largest dimension inside the 108 dp layer (safe zone is a 66 dp circle)
ART_CENTER_Y_DP = 55       # slightly below centre: the hair curl adds visual weight at the top


def hex_rgb(value):
    value = value.lstrip('#')
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def foreground_layer(size_px):
    """108 dp transparent layer with Purl and a soft contact shadow, rendered at size_px."""
    big = size_px * SS
    dp = big / 108.0
    layer = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    art = Image.open(SOURCE).convert('RGBA')
    scale = ART_MAX_DP * dp / max(art.size)
    w, h = round(art.width * scale), round(art.height * scale)
    art = art.resize((w, h), Image.LANCZOS)
    x = round((big - w) / 2)
    y = round(ART_CENTER_Y_DP * dp - h / 2)
    # Soft contact shadow under the feet.
    shadow = Image.new('L', (big, big), 0)
    sx0, sx1 = big / 2 - 0.36 * w, big / 2 + 0.36 * w
    sy = y + h - 0.035 * h
    ImageDraw.Draw(shadow).ellipse([sx0, sy - 0.05 * h, sx1, sy + 0.05 * h], fill=90)
    shadow = shadow.filter(ImageFilter.GaussianBlur(2.2 * dp))
    layer.paste((20, 30, 30, 255), (0, 0), shadow)
    layer.alpha_composite(art, (x, y))
    return layer.resize((size_px, size_px), Image.LANCZOS)


def legacy_icon(size_px, round_shape):
    """Pre-composited 48 dp icon: the central 72 dp of the adaptive layers, masked."""
    big = size_px * SS
    dp = big / 48.0
    inset = round(1 * dp)                   # 1 dp transparent margin
    shape_size = big - 2 * inset
    # Background with a gentle radial glow.
    bg = Image.new('RGBA', (shape_size, shape_size), hex_rgb(BACKGROUND_HEX) + (255,))
    glow = Image.new('L', (shape_size, shape_size), 0)
    r = shape_size * 0.42
    c = shape_size / 2
    ImageDraw.Draw(glow).ellipse([c - r, c - r * 1.05, c + r, c + r * 0.95], fill=200)
    glow = glow.filter(ImageFilter.GaussianBlur(shape_size * 0.16))
    bg.paste(BACKGROUND_INNER + (255,), (0, 0), glow)
    # Foreground: render the 108 dp layer so its central 72 dp spans the shape.
    fg_full = foreground_layer(round(shape_size * 108 / 72))
    off = (fg_full.width - shape_size) // 2
    fg = fg_full.crop((off, off, off + shape_size, off + shape_size))
    bg.alpha_composite(fg)
    mask = Image.new('L', (shape_size, shape_size), 0)
    draw = ImageDraw.Draw(mask)
    if round_shape:
        draw.ellipse([0, 0, shape_size - 1, shape_size - 1], fill=255)
    else:
        draw.rounded_rectangle([0, 0, shape_size - 1, shape_size - 1], radius=round(shape_size * 0.22), fill=255)
    out = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    bg.putalpha(ImageChops.multiply(bg.getchannel('A'), mask))
    out.alpha_composite(bg, (inset, inset))
    return out.resize((size_px, size_px), Image.LANCZOS)


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/generate-launcher-icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

COLOR_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/generate-launcher-icons.py -->
<resources>
    <color name="ic_launcher_background">{color}</color>
</resources>
"""


def main():
    if not SOURCE.is_file():
        sys.exit(f'missing source art: {SOURCE}')
    written = []
    for name, factor in DENSITIES.items():
        folder = RES / f'mipmap-{name}'
        folder.mkdir(parents=True, exist_ok=True)
        targets = {
            'ic_launcher_foreground.png': foreground_layer(round(108 * factor)),
            'ic_launcher.png': legacy_icon(round(48 * factor), round_shape=False),
            'ic_launcher_round.png': legacy_icon(round(48 * factor), round_shape=True),
        }
        for filename, image in targets.items():
            path = folder / filename
            image.save(path, optimize=True)
            written.append(path)
    anydpi = RES / 'mipmap-anydpi-v26'
    anydpi.mkdir(parents=True, exist_ok=True)
    for filename in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        (anydpi / filename).write_text(ADAPTIVE_XML, encoding='utf-8')
        written.append(anydpi / filename)
    values = RES / 'values'
    values.mkdir(parents=True, exist_ok=True)
    (values / 'ic_launcher_background.xml').write_text(COLOR_XML.format(color=BACKGROUND_HEX), encoding='utf-8')
    written.append(values / 'ic_launcher_background.xml')
    for path in written:
        print(path.relative_to(REPO))


if __name__ == '__main__':
    main()
